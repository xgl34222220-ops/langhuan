splash = Image.composite(Image.new('RGBA', splash.size, (6, 40, 30, 255)), Image.new('RGBA', splash.size, (0, 0, 0, 0)), sh)
splash.alpha_composite(tile, (off, off))
splash = splash.resize((C, C), Image.LANCZOS)
splash.save(os.path.join(res, 'drawable-nodpi', 'splash_glass_v97.png'), optimize=True)
