# ---------------------------------------------------------------- 5. splash icon (288 dp canvas)
# The glass art is near-white, so on the pale #EEF5F1 splash surface it is drawn on its own
# emerald tile (the launcher icon, superellipse) — 132 dp, well inside the 192 dp splash circle.
