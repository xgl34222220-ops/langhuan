# ---------------------------------------------------------------- 4. legacy, round, Play store
def squircle_mask(n, frac=1.0, ss=4):
    m = Image.new('L', (n * ss, n * ss), 0)
    s = n * ss * frac; o = (n * ss - s) / 2
    pts = []
    for i in range(720):
        t = 2 * math.pi * i / 720
        c, sn = math.cos(t), math.sin(t)
        x = abs(c) ** (2 / 5) * (1 if c >= 0 else -1); y = abs(sn) ** (2 / 5) * (1 if sn >= 0 else -1)
        pts.append((o + s / 2 + x * s / 2, o + s / 2 + y * s / 2))
    ImageDraw.Draw(m).polygon(pts, fill=255)
    return m.resize((n, n), Image.LANCZOS)

def circle_mask(n, frac=1.0, ss=4):
    m = Image.new('L', (n * ss, n * ss), 0); s = n * ss * frac; o = (n * ss - s) / 2
    ImageDraw.Draw(m).ellipse([o, o, o + s, o + s], fill=255)
    return m.resize((n, n), Image.LANCZOS)

